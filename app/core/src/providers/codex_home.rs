//! A Vajra-owned `CODEX_HOME` for the gateway provider (harness B).
//!
//! The Codex harness is pointed at a gateway through a generated `config.toml` in a folder Vajra owns, so the user's own
//! `~/.codex` is never read or written. The file holds nothing secret: the key stays in the Keychain, and Codex fetches
//! it by running `/usr/bin/security` (`auth.command`) each time it needs it. There is no `env_key`, so no key is ever in
//! the child's environment.

use std::fmt::Write as _;
use std::io;
use std::path::{Path, PathBuf};

use super::keychain::{self, SECURITY};

/// The provider id in the generated config. Never the user's own `openrouter` entry.
pub const PROVIDER_ID: &str = "vajra-openrouter";
/// Where the gateway answers, until an account carries its own non-secret `base_url`.
pub const DEFAULT_BASE_URL: &str = "https://openrouter.ai/api/v1";
/// The folder under the data dir that holds one `CODEX_HOME` per account.
const HOMES_DIR: &str = "codex-home";

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Error {
    /// The account has no stored key (only accounts in `keychain::KEY_ACCOUNTS` do).
    UnknownAccount,
    /// The base URL is not a plain `https://` URL.
    BadBaseUrl,
    Io(String),
}

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::UnknownAccount => f.write_str("account does not take a stored key"),
            Self::BadBaseUrl => f.write_str("base_url must be an https:// URL"),
            Self::Io(e) => write!(f, "could not write the Codex home: {e}"),
        }
    }
}

impl std::error::Error for Error {}

/// A base URL that can go inside a TOML basic string unescaped: `https://`, a host, printable ASCII, no quote,
/// backslash, whitespace or control character, and no userinfo (`@`), so a credential cannot ride in the config.
fn valid_base_url(url: &str) -> bool {
    url.len() <= 256
        && url.strip_prefix("https://").is_some_and(|rest| !rest.is_empty() && !rest.starts_with('/'))
        && url.bytes().all(|b| b.is_ascii_graphic() && !matches!(b, b'"' | b'\\' | b'@'))
}

/// The text of `config.toml` for `account`. Nothing in it is secret.
pub fn render(account: &str, base_url: &str) -> Result<String, Error> {
    if !valid_base_url(base_url) {
        return Err(Error::BadBaseUrl);
    }
    let service = keychain::service(account).map_err(|_| Error::UnknownAccount)?;
    let mut out = String::new();
    let _ = writeln!(out, "# Generated by Vajra Desktop; edits are overwritten at each launch.");
    let _ = writeln!(out, "model_provider = \"{PROVIDER_ID}\"");
    let _ = writeln!(out);
    let _ = writeln!(out, "[model_providers.{PROVIDER_ID}]");
    let _ = writeln!(out, "name = \"Gateway\"");
    let _ = writeln!(out, "base_url = \"{base_url}\"");
    let _ = writeln!(out, "wire_api = \"responses\"");
    let _ = writeln!(out);
    let _ = writeln!(out, "[model_providers.{PROVIDER_ID}.auth]");
    let _ = writeln!(out, "command = \"{SECURITY}\"");
    let _ = writeln!(out, "args = [\"find-generic-password\", \"-s\", \"{service}\", \"-a\", \"{account}\", \"-w\"]");
    Ok(out)
}

/// The `CODEX_HOME` for `account` under `data_dir`.
pub fn home_for(data_dir: &Path, account: &str) -> Result<PathBuf, Error> {
    keychain::service(account).map_err(|_| Error::UnknownAccount)?;
    Ok(data_dir.join(HOMES_DIR).join(account))
}

/// Create (mode 0700) the account's `CODEX_HOME` and write its `config.toml`; returns the folder. Rewritten at every
/// launch so a stale file never outlives a changed base URL.
pub fn write(data_dir: &Path, account: &str, base_url: &str) -> Result<PathBuf, Error> {
    use std::os::unix::fs::PermissionsExt;
    let text = render(account, base_url)?;
    let home = home_for(data_dir, account)?;
    let io_err = |e: io::Error| Error::Io(e.kind().to_string());
    crate::paths::ensure_private_dir(&home).map_err(io_err)?;
    let file = home.join("config.toml");
    std::fs::write(&file, text).map_err(io_err)?;
    std::fs::set_permissions(&file, std::fs::Permissions::from_mode(0o600)).map_err(io_err)?;
    Ok(home)
}

